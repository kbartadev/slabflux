#pragma once

#include <immintrin.h>

namespace slabflux::core {

    class integrity_seal {
        uint64_t running_hash_{0xBAADF00D};

    public:
        /**
         * @brief Updates the seal with the current cycle's outcome.
         * Uses the ultra-fast CRC32 hardware instruction.
         */
        inline void update(uint64_t lsn, uint64_t state_delta) noexcept {
            running_hash_ = _mm_crc32_u64(running_hash_, lsn);
            running_hash_ = _mm_crc32_u64(running_hash_, state_delta);
        }

        inline uint64_t get_seal() const noexcept { return running_hash_; }
    };
}
