#pragma once
#include <immintrin.h>
#include <cstdint>

namespace slabflux::core {

/**
 * @brief SIMD-optimized entity storage.
 * @details Uses Structure of Arrays (SoA) to enable AVX-512 batch processing.
 */
template<size_t EntityCount>
struct alignas(64) entity_component_slab {
    static_assert(EntityCount % 16 == 0, "EntityCount must be a multiple of 16 for AVX-512");

    float pos_x[EntityCount];
    float pos_y[EntityCount];
    float vel_x[EntityCount];
    float vel_y[EntityCount];
    
    // Bitmask for active entities (Structural Honesty)
    uint16_t active_mask[EntityCount / 16];
};

} // namespace slabflux::core