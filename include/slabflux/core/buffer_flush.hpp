#pragma once

#include <immintrin.h>

namespace slabflux::core {

    /**
     * @brief Forces the CPU to drain all Load/Store Fill Buffers.
     * @details Beyond sfence, a locked instruction acts as a total 
     * serialization point for the memory subsystem.
     */
    static inline void force_lfb_drain() noexcept {
        _mm_sfence();
        uint64_t dummy = 0;
        // Atomic operation on a dummy stack variable to trigger drain
        asm volatile ("lock; addq $0, %0" : "+m" (dummy) : : "memory");
    }
}
