#pragma once
#include <x86intrin.h>
#include <cstddef>

namespace slabflux::core {

/**
 * @brief Software prefetching logic for high-frequency ring buffers.
 * @tparam T The type of data in the ring.
 * @tparam Distance How many elements ahead to prefetch.
 */
template <typename T, size_t Distance>
struct prefetch_orchestrator {
    static inline void hint_next(T** ring, size_t current_idx, size_t mask) noexcept {
        size_t target_idx = (current_idx + Distance) & mask;
        void* ptr = ring[target_idx];
        if (ptr) [[likely]] {
            // _MM_HINT_T0: Prefetch into all cache levels
            _mm_prefetch(static_cast<const char*>(ptr), _MM_HINT_T0);
        }
    }
};

} // namespace slabflux::core
