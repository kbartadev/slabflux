#include <gtest/gtest.h>
#include "slabflux/core/string_chunk.hpp"

using namespace slabflux::core;

TEST(StringChunkTest, PhysicalLayoutInvariants) {
    // Invariant: Chunks must fit exactly into one cache line 
    // to prevent MESI thrashing during massive string mutations.
    EXPECT_EQ(sizeof(string_chunk), 64);
    
    string_chunk chunk;
    chunk.next_chunk_idx = string_chunk::END_OF_CHAIN;
    
    // Ensure index fits in 32-bit to preserve data payload area
    static_assert(sizeof(chunk.next_chunk_idx) == 4, "Index size breach!");
    EXPECT_EQ(sizeof(chunk.data), 48);
}